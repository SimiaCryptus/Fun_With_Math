/* =====================================================================
   algorithm-c.js — Algorithm C: the min-factor exponent-spine generator
   Specification: algorithm.md §4C, full treatment in min_factor.md.

   Min-factor normal form (Theorem 2.10 / Claim M1).  Every n > 1 is
   uniquely n = p^e·r with p = spf(n), e = v_p(n) and r in the monoid
   B_p generated by the primes > p.  Summing over e re-assembles
   p·A_p = Θ_p, so this is a *refinement* of Algorithm B's index, not a
   different partition.

   Wheeled relaxation.  B_p is replaced by

       B̃_p = {1} ∪ { r ≥ p : gcd(r,W) = 1, p ∤ r } ⊇ B_p ,

   and **layer** (p,e) is the stream p^e·B̃_p minus the single
   non-composite element p (the case e = 1, r = 1).  Both retained
   constraints are load-bearing: r ≥ p stops a layer claiming numbers
   whose smallest factor is r, and p ∤ r keeps the layers of one prime
   disjoint (drop it and p^k is claimed k times).

   Records are (value, p, p^e, e, r, mp) with value = p^e·r; `mp` is the
   skip cursor, a multiple of p with mp ≥ r, which makes `next_adm`
   O(1) amortised (§4C.1: the ratio of skips to wheel steps is
   1/(κ_W·p) < 1 for every p > p_w ≥ 13).

   A layer is opened by the pop of its own spine element p^e, so no
   global N decides how many layers a prime gets, and the activation of
   p still fires exactly at n = p².

   What it buys (§4C.5 / min_factor.md §8): NOT touches — ops_C equals
   ops_B to within Θ(N^{2/3}/log N) — but output.  Every rejected
   candidate is reported as (spf, v_p, cofactor); the spine records are
   exactly the prime powers, in order.
   ===================================================================== */
